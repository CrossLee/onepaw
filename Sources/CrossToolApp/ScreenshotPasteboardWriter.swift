import AppKit
import Foundation

enum ScreenshotPasteboardError: LocalizedError {
    case invalidPNG
    case writeFailed

    var errorDescription: String? {
        switch self {
        case .invalidPNG:
            return "截图 PNG 数据无效"
        case .writeFailed:
            return "系统剪贴板拒绝写入图片"
        }
    }
}

@MainActor
protocol ScreenshotPasteboardWriting {
    func writePNG(_ pngData: Data, tiffData: Data?) throws
}

/// Writes eager image bytes instead of a file URL so the pasteboard remains
/// usable after OnePaw removes its managed screenshot draft.
@MainActor
struct ScreenshotPasteboardWriter: ScreenshotPasteboardWriting {
    private static let pngSignature = Data([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    private let pasteboard: NSPasteboard
    private let marksAsAutoGenerated: Bool

    init(
        pasteboard: NSPasteboard = .general,
        marksAsAutoGenerated: Bool = false
    ) {
        self.pasteboard = pasteboard
        self.marksAsAutoGenerated = marksAsAutoGenerated
    }

    func writePNG(_ pngData: Data, tiffData: Data? = nil) throws {
        // Every input is a OnePaw-generated draft. Checking the signature is
        // enough to reject an obviously invalid payload without decoding a
        // potentially 20-megapixel image on the main thread before the editor
        // can appear.
        guard pngData.starts(with: Self.pngSignature) else {
            throw ScreenshotPasteboardError.invalidPNG
        }

        let item = NSPasteboardItem()
        // Clipboard history can inspect the lightweight type list before it
        // asks AppKit to hand the complete PNG back to the main thread. Mark
        // OnePaw-generated screenshots so that read is skipped; the eager PNG
        // and optional TIFF remain available to every paste destination.
        if marksAsAutoGenerated,
           !item.setData(
               Data(),
               forType: ClipboardHistoryPasteboardType.autoGenerated
           ) {
            throw ScreenshotPasteboardError.writeFailed
        }
        guard item.setData(pngData, forType: .png) else {
            throw ScreenshotPasteboardError.writeFailed
        }
        if let tiffData {
            item.setData(tiffData, forType: .tiff)
        }

        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            throw ScreenshotPasteboardError.writeFailed
        }
    }
}
